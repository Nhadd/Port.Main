import fs from 'node:fs';
import path from 'node:path';
import { root, pages } from './check.mjs';

const destination = path.resolve(root, 'dist');

// Preserve stale output outside the public directory. No files are deleted.
if (path.dirname(destination) !== root || path.basename(destination) !== 'dist') {
  throw new Error('Invalid build destination');
}

const publicNames = [...pages, 'assets', 'cv', 'pfp', 'pp'];

function filesAt(directory, prefix = '') {
  const files = [];

  for (const item of fs.readdirSync(directory, { withFileTypes: true })) {
    if (item.isSymbolicLink()) {
      throw new Error('Build paths cannot contain symbolic links');
    }

    const relative = prefix + item.name;

    if (item.isDirectory()) {
      files.push(...filesAt(path.join(directory, item.name), relative + '/'));
    } else if (item.isFile()) {
      files.push(relative);
    } else {
      throw new Error('Unsupported build entry');
    }
  }

  return files;
}

const expected = new Set([...pages, '.nojekyll', '.portfolio-build']);

for (const name of publicNames) {
  const source = path.join(root, name);
  const info = fs.lstatSync(source);

  if (info.isSymbolicLink()) {
    throw new Error('Build sources cannot be symbolic links');
  }

  if (info.isDirectory()) {
    for (const file of filesAt(source)) {
      expected.add(name + '/' + file);
    }
  }
}

if (fs.existsSync(destination)) {
  if (fs.lstatSync(destination).isSymbolicLink()) {
    throw new Error('Build destination cannot be a symbolic link');
  }

  const stale = filesAt(destination).filter(file => !expected.has(file));

  if (stale.length) {
    const backup = fs.mkdtempSync(
      path.join(root, '.portfolio-build-backups-')
    );

    for (const file of stale) {
      const from = path.resolve(destination, file);
      const to = path.resolve(backup, file);

      if (
        !from.startsWith(destination + path.sep)
        || !to.startsWith(backup + path.sep)
      ) {
        throw new Error('Invalid backup path');
      }

      fs.mkdirSync(path.dirname(to), { recursive: true });
      fs.renameSync(from, to);
    }

    console.log(
      `Preserved ${stale.length} stale build file(s) outside the Pages artifact: ${backup}`
    );
  }
}

const marker = path.join(destination, '.portfolio-build');

fs.mkdirSync(destination, { recursive: true });

fs.writeFileSync(
  marker,
  'Generated by scripts/build.mjs. Safe to regenerate.\n'
);

for (const name of publicNames) {
  fs.cpSync(
    path.join(root, name),
    path.join(destination, name),
    { recursive: true }
  );
}

fs.writeFileSync(path.join(destination, '.nojekyll'), '');

console.log(`Production static build ready: ${destination}`);
console.log('GitHub Pages artifact: PORT/dist/ -> https://nhadd.github.io/Port.Main/');
