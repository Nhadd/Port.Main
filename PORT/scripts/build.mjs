import fs from 'node:fs';
import path from 'node:path';
import { root, pages } from './check.mjs';
const destination = path.resolve(root, 'dist');
// Delete only this tool's previously marked output within the source directory.
if (path.dirname(destination) !== root || path.basename(destination) !== 'dist') throw new Error('Invalid build destination');
const marker = path.join(destination, '.portfolio-build');
if (fs.existsSync(destination)) {
  if (!fs.existsSync(marker)) throw new Error('dist exists without a build marker; refusing to replace it.');
  fs.rmSync(destination, { recursive: true });
}
fs.mkdirSync(destination);
fs.writeFileSync(marker, 'Generated by scripts/build.mjs. Safe to regenerate.\n');
for (const name of [...pages, '.nojekyll', 'assets', 'cv', 'pfp', 'pp']) {
  fs.cpSync(path.join(root, name), path.join(destination, name), { recursive: true });
}
console.log(`Production static build ready: ${destination}`);
console.log('Deploy the root source or contents of dist. Both support /leonarddacpano/.');
